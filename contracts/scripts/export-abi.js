// Writes the compiled ABI to the web app as a typed constant.
//   npx hardhat run scripts/export-abi.js
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");

async function main() {
  await hre.run("compile");
  const artifact = await hre.artifacts.readArtifact("Sambung");
  const out = path.join(__dirname, "..", "..", "web", "src", "config", "abi.ts");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(
    out,
    `// Generated by contracts/scripts/export-abi.js — do not edit by hand.\n` +
      `export const sambungAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`
  );
  console.log(`ABI written to ${path.relative(process.cwd(), out)} (${artifact.abi.length} entries)`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
